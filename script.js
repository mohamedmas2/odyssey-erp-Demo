const root = document.documentElement;
const body = document.body;
const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
const menuToggle = document.getElementById("menuToggle");
const nav = document.querySelector(".nav");
const form = document.querySelector(".demo-form");
const formMessage = document.getElementById("formMessage");

const savedLanguage = localStorage.getItem("odyssey-language") || "en";
const savedTheme = localStorage.getItem("odyssey-theme");
const systemPrefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;

function applyLanguage(language) {
  const content = translations[language];
  if (!content) return;

  root.lang = language;
  body.dir = language === "ar" ? "rtl" : "ltr";
  body.dataset.language = language;
  langToggle.textContent = language === "ar" ? "English" : "العربية";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (content[key]) {
      element.textContent = content[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (content[key]) {
      element.setAttribute("placeholder", content[key]);
    }
  });

  localStorage.setItem("odyssey-language", language);
}

function applyTheme(theme) {
  body.dataset.theme = theme;
  localStorage.setItem("odyssey-theme", theme);
}

langToggle.addEventListener("click", () => {
  applyLanguage(body.dataset.language === "ar" ? "en" : "ar");
});

themeToggle.addEventListener("click", () => {
  applyTheme(body.dataset.theme === "dark" ? "light" : "dark");
});

menuToggle.addEventListener("click", () => {
  nav.classList.toggle("is-open");
});

nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => nav.classList.remove("is-open"));
});

form.addEventListener("submit", (event) => {
  event.preventDefault();
  formMessage.textContent = translations[body.dataset.language].formSuccess;
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.16 }
);

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

applyLanguage(savedLanguage);
applyTheme(savedTheme || (systemPrefersDark ? "dark" : "light"));
